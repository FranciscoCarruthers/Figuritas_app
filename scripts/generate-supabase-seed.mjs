import fs from 'node:fs'

const EDITION_ID = 'fifa-world-cup-2026'
const source = fs.readFileSync('src/data/sticker-data.ts', 'utf8')
const checkOnly = process.argv.includes('--check')

function findArrayAfter(marker) {
  const markerIndex = source.indexOf(marker)
  if (markerIndex === -1) throw new Error(`Missing marker: ${marker}`)
  const assignmentIndex = source.indexOf('=', markerIndex)
  const start = source.indexOf('[', assignmentIndex)
  if (start === -1) throw new Error(`Missing array after: ${marker}`)

  let depth = 0
  let quote = null
  let escaped = false

  for (let index = start; index < source.length; index += 1) {
    const char = source[index]

    if (quote) {
      if (escaped) {
        escaped = false
      } else if (char === '\\') {
        escaped = true
      } else if (char === quote) {
        quote = null
      }
      continue
    }

    if (char === '\'' || char === '"') {
      quote = char
      continue
    }

    if (char === '[') depth += 1
    if (char === ']') depth -= 1
    if (depth === 0) return source.slice(start, index + 1)
  }

  throw new Error(`Unclosed array after: ${marker}`)
}

function parseArray(marker, context = {}) {
  const arrayText = findArrayAfter(marker)
  const names = Object.keys(context)
  const values = Object.values(context)
  return Function(...names, `"use strict"; return (${arrayText});`)(...values)
}

function sql(value) {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number') return String(value)
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  return `'${String(value).replaceAll('\'', '\'\'')}'`
}

function makeTeamStickers(team) {
  const stickers = []
  stickers.push({ code: `${team.code}1`, name: 'Team Logo', team: team.name, teamCode: team.code, type: 'logo', isFoil: true, position: 1 })
  for (let index = 0; index < 11; index += 1) {
    stickers.push({ code: `${team.code}${index + 2}`, name: team.players[index], team: team.name, teamCode: team.code, type: 'player', isFoil: false, position: index + 2 })
  }
  stickers.push({ code: `${team.code}13`, name: 'Team Photo', team: team.name, teamCode: team.code, type: 'photo', isFoil: false, position: 13 })
  for (let index = 11; index < 18; index += 1) {
    stickers.push({ code: `${team.code}${index + 3}`, name: team.players[index], team: team.name, teamCode: team.code, type: 'player', isFoil: false, position: index + 3 })
  }
  return stickers
}

const intro = parseArray('const INTRO_STICKERS')
const teams = parseArray('const TEAM_DATA')
const bonusTeam = { code: 'CC', name: 'Coca Cola' }
const bonus = parseArray('export const BONUS_STICKERS', { BONUS_TEAM: bonusTeam })

const sectionMatches = [...source.matchAll(/\{ label: '([^']+)', teams: (\[INTRO_TEAM\]|\[BONUS_TEAM\]|t\(([^)]*)\)) \}/g)]
const sections = sectionMatches.map((match, index) => ({
  id: `section-${String(index).padStart(2, '0')}`,
  label: match[1],
  teams: match[2] === '[INTRO_TEAM]'
    ? ['FWC']
    : match[2] === '[BONUS_TEAM]'
      ? [bonusTeam.code]
      : [...match[3].matchAll(/'([^']+)'/g)].map(codeMatch => codeMatch[1]),
}))

const teamByCode = new Map([...teams.map(team => [team.code, team]), [bonusTeam.code, bonusTeam]])
const teamSection = new Map()
for (const section of sections) {
  for (const code of section.teams) teamSection.set(code, section)
}

const coreStickerRows = [
  ...intro.map(sticker => ({
    ...sticker,
    team: 'Introducción',
    section: sections[0],
  })),
  ...teams.flatMap(team => makeTeamStickers(team).map(sticker => ({
    ...sticker,
    section: teamSection.get(team.code),
  }))),
]

const stickerRows = [
  ...coreStickerRows,
  ...bonus.map(sticker => ({
    ...sticker,
    section: teamSection.get(sticker.teamCode),
  })),
]

const codes = new Set(stickerRows.map(sticker => sticker.code))
const groupedTeamCodes = new Set(sections.flatMap(section => section.teams).filter(code => code !== 'FWC' && code !== bonusTeam.code))

if (intro.length !== 20) throw new Error(`Expected 20 intro stickers, got ${intro.length}`)
if (teams.length !== 48) throw new Error(`Expected 48 teams, got ${teams.length}`)
if (teams.some(team => team.players.length !== 18)) throw new Error('Every team must have 18 players')
if (coreStickerRows.length !== 980) throw new Error(`Expected 980 core stickers, got ${coreStickerRows.length}`)
if (bonus.length !== 14) throw new Error(`Expected 14 bonus stickers, got ${bonus.length}`)
if (stickerRows.length !== 994) throw new Error(`Expected 994 stickers, got ${stickerRows.length}`)
if (codes.size !== stickerRows.length) throw new Error('Sticker codes are not unique')
if (groupedTeamCodes.size !== 48) throw new Error(`Expected 48 grouped teams, got ${groupedTeamCodes.size}`)
if (!teamSection.get(bonusTeam.code)) throw new Error('Missing Coca Cola bonus section')

if (!checkOnly) {
  const lines = [
    '-- Generated by scripts/generate-supabase-seed.mjs',
    'begin;',
    '',
    `insert into album_editions (id, name, total_stickers) values (${sql(EDITION_ID)}, ${sql('FIFA World Cup 2026')}, 980) on conflict (id) do update set name = excluded.name, total_stickers = excluded.total_stickers;`,
    '',
    'insert into sections (id, edition_id, name, sort_order) values',
    sections.map((section, index) => `  (${sql(section.id)}, ${sql(EDITION_ID)}, ${sql(section.label)}, ${index})`).join(',\n') + '\non conflict (id) do update set name = excluded.name, sort_order = excluded.sort_order;',
    '',
    'insert into teams (code, edition_id, section_id, name, sort_order) values',
    sections.flatMap(section => section.teams.map((code, index) => {
      const team = code === 'FWC' ? { code: 'FWC', name: 'Introducción' } : teamByCode.get(code)
      return `  (${sql(code)}, ${sql(EDITION_ID)}, ${sql(section.id)}, ${sql(team.name)}, ${index})`
    })).join(',\n') + '\non conflict (code) do update set section_id = excluded.section_id, name = excluded.name, sort_order = excluded.sort_order;',
    '',
    'insert into stickers (code, edition_id, section_id, team_code, team_name, name, sticker_type, is_foil, position) values',
    stickerRows.map(sticker => `  (${sql(sticker.code)}, ${sql(EDITION_ID)}, ${sql(sticker.section.id)}, ${sql(sticker.teamCode)}, ${sql(sticker.team)}, ${sql(sticker.name)}, ${sql(sticker.type)}, ${sql(sticker.isFoil)}, ${sql(sticker.position)})`).join(',\n') + '\non conflict (code) do update set section_id = excluded.section_id, team_code = excluded.team_code, team_name = excluded.team_name, name = excluded.name, sticker_type = excluded.sticker_type, is_foil = excluded.is_foil, position = excluded.position;',
    '',
    'commit;',
    '',
  ]

  fs.writeFileSync('supabase/seed.sql', lines.join('\n'))
}

console.log(`Validated ${coreStickerRows.length} core stickers, ${bonus.length} bonus stickers, ${stickerRows.length} total stickers, ${teams.length} teams, ${sections.length} sections.`)
